"""Writes demo/iceberg_demo.sql for Blason's Iceberg demo, with the real Phase 0 / Phase 1 snapshot
ids of lake.search.documents taken from lake.search.ingest_log. Rerun after every rehearsal reset.

  spark-submit demo/make_iceberg_demo.py            # cluster
  spark-submit demo/make_iceberg_demo.py --local    # local warehouse
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "node3_compute"))
from common_spark import get_spark  # noqa: E402

OUT = Path(__file__).resolve().parent / "iceberg_demo.sql"


def snapshot_for(spark, phase):
    rows = (spark.table("lake.search.ingest_log").where(f"phase = {phase}")
            .orderBy("run_at", ascending=False).limit(1).collect())
    return rows[0]["documents_snapshot_id"] if rows else None


def main():
    spark = get_spark("make-iceberg-demo", "--local" in sys.argv)
    p0, p1 = snapshot_for(spark, 0), snapshot_for(spark, 1)
    if p0 is None:
        raise SystemExit("no phase 0 row in ingest_log yet; run Phase 0 first")
    p1_text = p1 if p1 is not None else "<phase1_snapshot_id: run Phase 1, then rerun this script>"

    OUT.write_text(f"""-- Iceberg demo for node2 (Blason). Generated by demo/make_iceberg_demo.py, do not edit by hand.
-- Open:  spark-sql --master spark://node3:7077     then paste one statement at a time.
-- Phase 0 snapshot of documents: {p0}
-- Phase 1 snapshot of documents: {p1_text}

-- 1. History: every change to the table is a snapshot
SELECT snapshot_id, committed_at, operation FROM lake.search.documents.snapshots ORDER BY committed_at;

-- 2. Time travel: document count now vs. right after Phase 0
SELECT count(*) FROM lake.search.documents;
SELECT count(*) FROM lake.search.documents VERSION AS OF {p0};

-- 3. What Phase 1 changed (rows in the current table that differ from Phase 0)
SELECT doc_id, title, version FROM lake.search.documents
EXCEPT
SELECT doc_id, title, version FROM lake.search.documents VERSION AS OF {p0};

-- 4. Rollback ONLY if the evaluator asks, and ALWAYS roll forward again right after:
-- CALL lake.system.rollback_to_snapshot('search.documents', {p0});
-- SELECT count(*) FROM lake.search.documents;
-- CALL lake.system.set_current_snapshot('search.documents', {p1_text});
""")
    print(f"wrote {OUT} (phase0={p0}, phase1={p1})")


if __name__ == "__main__":
    main()
